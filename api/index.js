let sql;
let schemaPromise;

class HttpError extends Error {
  constructor(status, message) {
    super(message);
    this.status = status;
  }
}

function getSql() {
  if (!process.env.DATABASE_URL) {
    throw new HttpError(503, "Guest storage is not configured. Set DATABASE_URL in Vercel.");
  }
  if (!sql) sql = neon(process.env.DATABASE_URL);
  return sql;
}

async function ensureSchema(db) {
  if (!schemaPromise) {
    schemaPromise = (async () => {
      await db`
        CREATE TABLE IF NOT EXISTS wedding_guests (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name TEXT NOT NULL,
          token_hash TEXT NOT NULL UNIQUE,
          expires_at TIMESTAMPTZ,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `;
      await db`
        CREATE TABLE IF NOT EXISTS wedding_guest_events (
          guest_id BIGINT NOT NULL REFERENCES wedding_guests(id) ON DELETE CASCADE,
          event_id TEXT NOT NULL CHECK (event_id IN ('mehndi', 'barat', 'walima')),
          PRIMARY KEY (guest_id, event_id)
        )
      `;
      await db`
        CREATE TABLE IF NOT EXISTS wedding_admin_sessions (
          token_hash TEXT PRIMARY KEY,
          expires_at TIMESTAMPTZ NOT NULL
        )
      `;
      await db`
        CREATE TABLE IF NOT EXISTS wedding_login_attempts (
          address_hash TEXT PRIMARY KEY,
          attempts INTEGER NOT NULL,
          window_started_at TIMESTAMPTZ NOT NULL
        )
      `;
    })().catch((error) => {
      schemaPromise = undefined;
      throw error;
    });
  }
  await schemaPromise;
}

function json(res, status, payload, headers = {}) {
  res.statusCode = status;
  res.setHeader("Content-Type", "application/json; charset=utf-8");
  res.setHeader("Cache-Control", "no-store");
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.setHeader("Referrer-Policy", "no-referrer");
  Object.entries(headers).forEach(([name, value]) => res.setHeader(name, value));
  res.end(JSON.stringify(payload));
}

function routePath(req) {
  const path = req.query && req.query.path;
  if (Array.isArray(path)) return `/${path.join("/")}`;
  if (typeof path === "string" && path) return `/${path}`;
  return "/";
}

async function readJson(req) {
  const declaredLength = Number(req.headers["content-length"] || 0);
  if (declaredLength > MAX_BODY_BYTES) {
    throw new HttpError(413, "Request body is too large.");
  }

  if (req.body !== undefined) {
    const raw = typeof req.body === "string" ? req.body : JSON.stringify(req.body);
    if (Buffer.byteLength(raw) > MAX_BODY_BYTES) {
      throw new HttpError(413, "Request body is too large.");
    }
    try {
      const payload = typeof req.body === "string" ? JSON.parse(req.body) : req.body;
      if (!payload || Array.isArray(payload) || typeof payload !== "object") {
        throw new HttpError(400, "Invalid request body.");
      }
      return payload;
    } catch (error) {
      if (error instanceof HttpError) throw error;
      throw new HttpError(400, "Invalid JSON.");
    }
  }

  const chunks = [];
  let size = 0;
  for await (const chunk of req) {
    size += chunk.length;
    if (size > MAX_BODY_BYTES) throw new HttpError(413, "Request body is too large.");
    chunks.push(chunk);
  }
  try {
    const payload = JSON.parse(Buffer.concat(chunks).toString("utf8"));
    if (!payload || Array.isArray(payload) || typeof payload !== "object") {
      throw new HttpError(400, "Invalid request body.");
    }
    return payload;
  } catch (error) {
    if (error instanceof HttpError) throw error;
    throw new HttpError(400, "Invalid JSON.");
  }
}

function checkOrigin(req) {
  const origin = req.headers.origin;
  const host = req.headers.host;
  if (!origin || !host) throw new HttpError(403, "Request origin was not accepted.");
  try {
    if (new URL(origin).host.toLowerCase() !== host.toLowerCase()) {
      throw new HttpError(403, "Request origin was not accepted.");
    }
  } catch (error) {
    if (error instanceof HttpError) throw error;
    throw new HttpError(403, "Request origin was not accepted.");
  }
}

function getSessionToken(req) {
  const cookies = (req.headers.cookie || "").split(";");
  const cookie = cookies.find((item) => item.trim().startsWith("wedding_admin="));
  if (!cookie) return "";
  return cookie.trim().slice("wedding_admin=".length);
}

async function requireAdmin(req, db) {
  const token = getSessionToken(req);
  if (!/^[a-f0-9]{64}$/.test(token)) {
    throw new HttpError(401, "Please sign in to manage invitations.");
  }
  const tokenHash = crypto.createHash("sha256").update(token).digest("hex");
  const sessions = await db`
    SELECT token_hash
    FROM wedding_admin_sessions
    WHERE token_hash = ${tokenHash} AND expires_at > NOW()
  `;
  if (!sessions.length) throw new HttpError(401, "Please sign in to manage invitations.");
  return tokenHash;
}

function validateGuest(payload) {
  const name = payload.name;
  const suppliedEvents = payload.events;
  const expiryValue = payload.expiresAt;
  if (typeof name !== "string" || !name.trim() || name.trim().length > 120) {
    throw new HttpError(400, "Enter a guest or family name (up to 120 characters).");
  }
  if (!Array.isArray(suppliedEvents) || suppliedEvents.length === 0) {
    throw new HttpError(400, "Assign at least one wedding event.");
  }
  if (suppliedEvents.some((event) => typeof event !== "string" || !EVENTS[event])) {
    throw new HttpError(400, "Choose valid wedding events.");
  }

  let expiresAt = null;
  if (expiryValue !== null && expiryValue !== undefined && expiryValue !== "") {
    if (typeof expiryValue !== "string" || !Number.isFinite(Date.parse(expiryValue))) {
      throw new HttpError(400, "Choose a valid expiry date.");
    }
    const date = new Date(expiryValue);
    if (date.getTime() <= Date.now()) {
      throw new HttpError(400, "Expiry must be a future date.");
    }
    expiresAt = date.toISOString();
  }

  return {
    name: name.trim(),
    events: [...new Set(suppliedEvents)],
    expiresAt
  };
}

function orderEvents(events) {
  const order = { mehndi: 0, barat: 1, walima: 2 };
  return events.sort((left, right) => order[left.event_id] - order[right.event_id]);
}

async function getInvitation(db, token, res) {
  if (!/^[a-f0-9]{64}$/.test(token)) {
    return json(res, 404, { error: "This invitation link is invalid or expired." });
  }
  const tokenHash = crypto.createHash("sha256").update(token).digest("hex");
  const guests = await db`
    SELECT id, name, expires_at
    FROM wedding_guests
    WHERE token_hash = ${tokenHash}
  `;
  if (!guests.length) {
    return json(res, 404, { error: "This invitation link is invalid or expired." });
  }
  const guest = guests[0];
  if (guest.expires_at && new Date(guest.expires_at).getTime() <= Date.now()) {
    return json(res, 410, { error: "This invitation link has expired." });
  }
  const rows = await db`
    SELECT event_id
    FROM wedding_guest_events
    WHERE guest_id = ${guest.id}
  `;
  const events = orderEvents(rows).map(({ event_id }) => ({
    id: event_id,
    ...EVENTS[event_id]
  }));
  if (!events.length) {
    return json(res, 404, { error: "This invitation link is invalid or expired." });
  }
  return json(res, 200, { guestName: guest.name, events });
}

async function listGuests(db, res) {
  const guests = await db`
    SELECT
      g.id::text AS id,
      g.name,
      g.expires_at AS "expiresAt",
      g.created_at AS "createdAt",
      COALESCE(
        ARRAY_AGG(ge.event_id) FILTER (WHERE ge.event_id IS NOT NULL),
        ARRAY[]::TEXT[]
      ) AS events
    FROM wedding_guests g
    LEFT JOIN wedding_guest_events ge ON ge.guest_id = g.id
    GROUP BY g.id
    ORDER BY LOWER(g.name)
  `;
  return json(res, 200, { guests, events: EVENTS });
}

function cookieOptions(maxAge) {
  return [
    "Path=/",
    "HttpOnly",
    "SameSite=Strict",
    `Max-Age=${maxAge}`,
    ...(process.env.VERCEL ? ["Secure"] : [])
  ].join("; ");
}

function getClientAddress(req) {
  const forwarded = req.headers["x-forwarded-for"];
  if (typeof forwarded === "string" && forwarded.trim()) {
    return forwarded.split(",")[0].trim();
  }
  return req.socket && req.socket.remoteAddress
    ? req.socket.remoteAddress
    : "unknown";
}

async function checkLoginRateLimit(db, req) {
  const addressHash = crypto
    .createHash("sha256")
    .update(getClientAddress(req))
    .digest("hex");
  const rows = await db`
    INSERT INTO wedding_login_attempts (address_hash, attempts, window_started_at)
    VALUES (${addressHash}, 1, NOW())
    ON CONFLICT (address_hash) DO UPDATE SET
      attempts = CASE
        WHEN wedding_login_attempts.window_started_at <= NOW() - INTERVAL '15 minutes'
          THEN 1
        ELSE wedding_login_attempts.attempts + 1
      END,
      window_started_at = CASE
        WHEN wedding_login_attempts.window_started_at <= NOW() - INTERVAL '15 minutes'
          THEN NOW()
        ELSE wedding_login_attempts.window_started_at
      END
    RETURNING attempts
  `;
  if (rows[0].attempts > 5) {
    throw new HttpError(429, "Too many sign-in attempts. Try again in 15 minutes.");
  }
  return addressHash;
}

async function login(db, req, res) {
  const configuredPassword = process.env.WEDDING_ADMIN_PASSWORD;
  if (!configuredPassword || configuredPassword.length < 16) {
    throw new HttpError(503, "Set WEDDING_ADMIN_PASSWORD to at least 16 characters in Vercel.");
  }
  const addressHash = await checkLoginRateLimit(db, req);
  const payload = await readJson(req);
  const password = payload.password;
  const supplied = typeof password === "string" ? Buffer.from(password) : Buffer.alloc(0);
  const expected = Buffer.from(configuredPassword);
  const accepted =
    supplied.length === expected.length &&
    crypto.timingSafeEqual(supplied, expected);
  if (!accepted) throw new HttpError(401, "The admin password was not accepted.");

  await db`
    DELETE FROM wedding_login_attempts
    WHERE address_hash = ${addressHash}
  `;
  const token = crypto.randomBytes(32).toString("hex");
  const tokenHash = crypto.createHash("sha256").update(token).digest("hex");
  await db`
    INSERT INTO wedding_admin_sessions (token_hash, expires_at)
    VALUES (${tokenHash}, NOW() + INTERVAL '8 hours')
  `;
  return json(
    res,
    200,
    { ok: true },
    { "Set-Cookie": `wedding_admin=${token}; ${cookieOptions(SESSION_TTL_SECONDS)}` }
  );
}

async function createGuest(db, req, res) {
  const guest = validateGuest(await readJson(req));
  const token = crypto.randomBytes(32).toString("hex");
  const tokenHash = crypto.createHash("sha256").update(token).digest("hex");
  const assignments = guest.events.map((eventId) => db`
    INSERT INTO wedding_guest_events (guest_id, event_id)
    SELECT id, ${eventId}
    FROM wedding_guests
    WHERE token_hash = ${tokenHash}
  `);
  const [created] = await db.transaction([
    db`
      INSERT INTO wedding_guests (name, token_hash, expires_at)
      VALUES (${guest.name}, ${tokenHash}, ${guest.expiresAt})
      RETURNING id::text AS id
    `,
    ...assignments
  ]);
  return json(res, 201, {
    id: created[0].id,
    name: guest.name,
    events: guest.events,
    expiresAt: guest.expiresAt,
    invitationPath: `/invite/${token}`
  });
}

async function updateGuest(db, guestId, req, res) {
  const guest = validateGuest(await readJson(req));
  const assignments = guest.events.map((eventId) => db`
    INSERT INTO wedding_guest_events (guest_id, event_id)
    VALUES (${guestId}, ${eventId})
  `);
  const [updated] = await db.transaction([
    db`
      UPDATE wedding_guests
      SET name = ${guest.name}, expires_at = ${guest.expiresAt}, updated_at = NOW()
      WHERE id = ${guestId}
      RETURNING id
    `,
    db`DELETE FROM wedding_guest_events WHERE guest_id = ${guestId}`,
    ...assignments
  ]);
  if (!updated.length) return json(res, 404, { error: "Guest not found." });
  return json(res, 200, { ok: true });
}

async function handle(req, res) {
  const path = routePath(req);
  const method = (req.method || "GET").toUpperCase();
  const invitationMatch = path.match(/^\/invitations\/([a-f0-9]{64})$/);
  if (method === "GET" && invitationMatch) {
    const db = getSql();
    await ensureSchema(db);
    return getInvitation(db, invitationMatch[1], res);
  }

  const db = getSql();
  await ensureSchema(db);

  if (method === "GET" && path === "/admin/guests") {
    await requireAdmin(req, db);
    return listGuests(db, res);
  }

  if (method === "POST") {
    checkOrigin(req);
    if (path === "/admin/login") return login(db, req, res);
    if (path === "/admin/logout") {
      const tokenHash = await requireAdmin(req, db);
      await db`DELETE FROM wedding_admin_sessions WHERE token_hash = ${tokenHash}`;
      return json(
        res,
        200,
        { ok: true },
        { "Set-Cookie": `wedding_admin=; ${cookieOptions(0)}` }
      );
    }
    if (path === "/admin/guests") {
      await requireAdmin(req, db);
      return createGuest(db, req, res);
    }
  }

  const guestMatch = path.match(/^\/admin\/guests\/([0-9]+)$/);
  if (guestMatch && (method === "PUT" || method === "DELETE")) {
    checkOrigin(req);
    await requireAdmin(req, db);
    if (method === "PUT") return updateGuest(db, guestMatch[1], req, res);
    const deleted = await db`
      DELETE FROM wedding_guests
      WHERE id = ${guestMatch[1]}
      RETURNING id
    `;
    if (!deleted.length) return json(res, 404, { error: "Guest not found." });
    return json(res, 200, { ok: true });
  }

  return json(res, 404, { error: "Page not found." });
}

module.exports = async function handler(req, res) {
  try {
    await handle(req, res);
  } catch (error) {
    if (error instanceof HttpError) {
      return json(res, error.status, { error: error.message });
    }
    console.error("Invitation API request failed", {
      name: error && error.name,
      code: error && error.code
    });
    return json(res, 500, { error: "The invitation service could not complete the request." });
  }
};
